import assert from 'node:assert/strict';
import { isInstitutionalDisplacement } from '../../src/engine/smc/math/directional_impulse.js';
import type { OHLCV, DirectionalImpulseSnapshot } from '../../src/engine/smc/types.js';
const candle: OHLCV = { timestamp: 1, open: 10.2, close: 10.8, high: 11, low: 10, volume: 0 };
const snapshot: DirectionalImpulseSnapshot = { timestamp: 1, sampleCount: 50, ready: true, zUp: 1.35, zDn: -4, upSmooth: 1, dnSmooth: .1, atr: 1, atrNormalizedRange: 1, volumeRatio: 1, priorVolumeMean: null };
assert.equal(isInstitutionalDisplacement(candle, 1, 'Bullish', null), true);
assert.equal(isInstitutionalDisplacement(candle, 1, 'Bullish', snapshot, 1), true);
assert.equal(isInstitutionalDisplacement(candle, 1, 'Bullish', { ...snapshot, zUp: 1.34 }, 1), false);
assert.equal(isInstitutionalDisplacement(candle, 1, 'Bullish', { ...snapshot, ready: false }), true);
assert.equal(isInstitutionalDisplacement(candle, 1, 'Bullish', { ...snapshot, ready: false }, 1), false);
assert.equal(isInstitutionalDisplacement(candle, 1, 'Bearish', snapshot), false);
assert.equal(isInstitutionalDisplacement(candle, 1, 'Bullish', { ...snapshot, timestamp: 0 }), false);
assert.equal(isInstitutionalDisplacement(candle, 1, 'Bullish', { ...snapshot, atr: 2 }), false);
assert.equal(isInstitutionalDisplacement({ ...candle, open: 10.4 }, 1, 'Bullish', snapshot), false);
assert.equal(isInstitutionalDisplacement({ ...candle, high: 10 }, 1, 'Bullish', snapshot), false);
assert.equal(isInstitutionalDisplacement(candle, 0, 'Bullish', null), false);
assert.equal(isInstitutionalDisplacement(candle, 1, 'Bullish', { ...snapshot, zUp: NaN }), false);
const bear = { ...candle, open: 20-candle.open, close: 20-candle.close, high: 20-candle.low, low: 20-candle.high };
assert.equal(isInstitutionalDisplacement(bear, 1, 'Bearish', { ...snapshot, zDn: 1.35, zUp: -4 }, 1), true);
assert.equal(isInstitutionalDisplacement(bear, 1, 'Bearish', snapshot, 1), false);
console.log('PASS displacement directional/color/body/causal/ATR warmup paths');
