import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {parseSmcExportArgs,assertLegacyDetectionSearch,assertResearchDestination,rejectLegacyDetectionProfileFlags} from '../smc_export_context.ts';
import * as smcExportContext from '../smc_export_context.ts';
assert.throws(()=>rejectLegacyDetectionProfileFlags(['EURUSD','tune','1','--profile','directional_atr_v1']),/isolated exporter/);
assert.doesNotThrow(()=>rejectLegacyDetectionProfileFlags(['EURUSD','tune','1']));
const root='/opt/JARVIS';
const legacy=parseSmcExportArgs(['EURUSD'],root);
assert.equal(legacy.profile,undefined);
assert.equal(legacy.outputDir,path.join(root,'logs/eurusd/history_exported'));
assert.equal(legacy.isolated,false);
assert.throws(()=>parseSmcExportArgs(['EURUSD','--profile','directional_atr_v1'],root),/output-dir/);
assert.throws(()=>parseSmcExportArgs(['EURUSD','--profile','typo','--output-dir','/tmp/smc-out'],root),/profile/);
assert.throws(()=>parseSmcExportArgs(['EURUSD','--output-dir',root+'/logs/eurusd/history_exported'],root),/outside/);
assert.throws(()=>parseSmcExportArgs(['../EURUSD'],root),/ticker/);
assert.throws(()=>parseSmcExportArgs(['EURUSD','--unknown'],root),/unknown/);
assert.throws(()=>parseSmcExportArgs(['EURUSD','--profile'],root),/value/);
const args=parseSmcExportArgs(['EURUSD','--profile','directional_atr_v1','--input-dir','/tmp/frozen','--output-dir','/tmp/smc-out','--timeframes','M5,H1','--quiet'],root);
assert.equal(args.isolated,true);assert.equal(args.quiet,true);
assert.deepEqual(args.timeframes,['M5','H1']);assert.equal(args.inputDir,'/tmp/frozen');
assert.doesNotThrow(()=>assertLegacyDetectionSearch({}));
assert.throws(()=>assertLegacyDetectionSearch({signal_profile:'directional_atr_v1'}),/isolated exporter/);
const tmp=fs.mkdtempSync(path.join(os.tmpdir(),'smc-path-test-'));
try{fs.symlinkSync(root,path.join(tmp,'repo'));
 assert.throws(()=>assertResearchDestination(path.join(tmp,'repo/logs/new'),root),/outside/);
 const raw=path.join(tmp,'raw');fs.mkdirSync(raw);
 const alias=path.join(tmp,'raw-link');fs.symlinkSync(raw,alias,'dir');
 const nested=path.join(alias,'not-created','deeper');
 assert.throws(()=>parseSmcExportArgs(['EURUSD','--input-dir',raw,'--output-dir',nested],root),/frozen|input directory|raw/i);
 assert.throws(()=>parseSmcExportArgs(['EURUSD','--input-dir',raw,'--output-dir',path.join(tmp,'outside'),'--manifest-out',path.join(alias,'not-created','manifest.json')],root),/frozen|input directory|raw/i);
 const assertFrozenInputIsolation=smcExportContext.assertFrozenInputIsolation;
 assert.equal(typeof assertFrozenInputIsolation,'function');
 assert.throws(()=>assertFrozenInputIsolation(raw,nested),/frozen|input directory|raw/i);
 assert.throws(()=>assertFrozenInputIsolation(alias,raw),/frozen|input directory|raw/i);
 const external=path.join(tmp,'raw-sibling','new','output');
 assert.doesNotThrow(()=>assertFrozenInputIsolation(raw,external));
 assert.equal(parseSmcExportArgs(['EURUSD','--input-dir',raw,'--output-dir',external],root).outputDir,external);
 const file=path.join(raw,'history_M5.csv');fs.writeFileSync(file,'frozen fixture');
 const fileAlias=path.join(tmp,'csv-link');fs.symlinkSync(file,fileAlias);
 assert.throws(()=>assertFrozenInputIsolation(raw,fileAlias),/frozen|input directory|raw/i);
 assert.throws(()=>assertFrozenInputIsolation(path.join(tmp,'missing-input'),external),/ENOENT/);
 const dangling=path.join(tmp,'dangling');fs.symlinkSync(path.join(raw,'missing'),dangling);
 assert.throws(()=>assertFrozenInputIsolation(raw,dangling),/ENOENT/);
 assert.deepEqual(fs.readdirSync(raw),['history_M5.csv']);
 console.log('PASS physical raw guard: nested symlink targets rejected; external output allowed; resolution errors fail closed');
}finally{fs.rmSync(tmp,{recursive:true,force:true});}
console.log('SMC isolated export argument and path tests passed');
